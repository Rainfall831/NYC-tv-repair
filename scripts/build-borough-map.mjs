// Builds simplified SVG paths for the five NYC boroughs from the NYC Department of
// City Planning borough boundaries (public domain, mirrored at dwillis/nyc-maps).
// Output: src/content/borough-paths.generated.ts
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { geoMercator, geoPath } from "d3-geo";

const SOURCE = "https://raw.githubusercontent.com/dwillis/nyc-maps/master/boroughs.geojson";
const WIDTH = 800;
const HEIGHT = 800;
const TOLERANCE = 0.9; // px, Douglas-Peucker
const MIN_AREA = 6; // px², drops tiny islands

const SLUG = {
  "Staten Island": "staten-island",
  Brooklyn: "brooklyn",
  Queens: "queens",
  Manhattan: "manhattan",
  Bronx: "bronx",
};

const root = path.resolve(import.meta.dirname, "..");
const geo = await (await fetch(SOURCE)).json();

const projection = geoMercator().fitExtent(
  [
    [10, 10],
    [WIDTH - 10, HEIGHT - 10],
  ],
  geo,
);

function perpDist(p, a, b) {
  const [x, y] = p;
  const [x1, y1] = a;
  const [x2, y2] = b;
  const dx = x2 - x1;
  const dy = y2 - y1;
  const len = dx * dx + dy * dy;
  if (len === 0) return Math.hypot(x - x1, y - y1);
  const t = Math.max(0, Math.min(1, ((x - x1) * dx + (y - y1) * dy) / len));
  return Math.hypot(x - (x1 + t * dx), y - (y1 + t * dy));
}

function simplify(points, tol) {
  if (points.length < 3) return points;
  let maxD = 0;
  let idx = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const d = perpDist(points[i], points[0], points[points.length - 1]);
    if (d > maxD) {
      maxD = d;
      idx = i;
    }
  }
  if (maxD <= tol) return [points[0], points[points.length - 1]];
  const left = simplify(points.slice(0, idx + 1), tol);
  const right = simplify(points.slice(idx), tol);
  return left.slice(0, -1).concat(right);
}

function area(ring) {
  let a = 0;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    a += (ring[j][0] + ring[i][0]) * (ring[j][1] - ring[i][1]);
  }
  return Math.abs(a / 2);
}

const r = (n) => Math.round(n * 10) / 10;
const out = [];

for (const feature of geo.features) {
  const name = feature.properties.BoroName;
  const polys = feature.geometry.type === "MultiPolygon" ? feature.geometry.coordinates : [feature.geometry.coordinates];
  let d = "";
  for (const poly of polys) {
    for (const ring of poly) {
      const projected = ring.map((c) => projection(c));
      if (area(projected) < MIN_AREA) continue;
      const s = simplify(projected, TOLERANCE);
      if (s.length < 4) continue;
      d += "M" + s.map(([x, y]) => `${r(x)} ${r(y)}`).join("L") + "Z";
    }
  }
  const [cx, cy] = geoPath(projection).centroid(feature);
  out.push({ slug: SLUG[name], name, d, label: [Math.round(cx), Math.round(cy)] });
}

out.sort((a, b) => a.name.localeCompare(b.name));

const file = `// Generated by scripts/build-borough-map.mjs from NYC DCP borough boundaries. Do not edit.
export const MAP_VIEWBOX = "0 0 ${WIDTH} ${HEIGHT}";

export const BOROUGH_PATHS = ${JSON.stringify(out, null, 2)} as const;
`;
await writeFile(path.join(root, "src", "content", "borough-paths.generated.ts"), file);
console.log(out.map((b) => `${b.name}: ${b.d.length} chars`).join("\n"));
